// Dev-only checks the smoke test (tools/smoke.py) runs on the headless server; never part of the pack.
// A failure is thrown, so KubeJS logs it as an error and the smoke test fails.
//
// Recipe-viewer mixins: GregTech bundles ModularUI, whose mixins into JEI's recipe layout classes
// only run when those classes load, which on a client happens the first time EMI draws a JEI-plugin
// recipe (all of Create's). If one fails, every such recipe shows "render failure" in EMI. Loading
// the classes here applies the same mixins on the server, so a JEI or GregTech update that breaks
// them shows up in the smoke test. (JEI 19.50+ removed a field ModularUI 3.3.1 needs; see
// docs/design.md, "Upstream issues".)
ServerEvents.loaded(event => {
  ;['mezz.jei.library.gui.ingredients.RecipeSlot', 'mezz.jei.library.gui.recipes.RecipeLayout',
    'mezz.jei.library.gui.recipes.layout.builder.RecipeLayoutBuilder', 'mezz.jei.gui.recipes.RecipeGuiLogic'].forEach(name => {
    Java.loadClass(name)
  })
  console.info('[smoke-checks] JEI recipe layout classes load with their mixins')

  // Quest book (generated by tools/quests/build.py): every item task names an item that exists (an
  // unknown id loads as an empty, uncompletable task), and every FTB Filter System expression parses
  // (one unknown id breaks the whole filter). FTB Quests loads its book after this event.
  event.server.scheduleInTicks(20, () => {
    var questFile = Java.loadClass('dev.ftb.mods.ftbquests.quest.ServerQuestFile').INSTANCE
    var filters = Java.loadClass('dev.ftb.mods.ftbfiltersystem.api.FTBFilterSystemAPI').api()
    var tasks = questFile.collect(Java.loadClass('dev.ftb.mods.ftbquests.quest.task.ItemTask'))
    var bad = []
    var filterCount = 0
    tasks.forEach(task => {
      var where = `${task.getQuest().getTitle().getString()} (${task.getQuest().getCodeString()})`
      var stack = task.getItemStack()
      if (stack.isEmpty()) {
        bad.push(`${where}: item task with no item`)
      } else if (filters.isFilterItem(stack)) {
        filterCount++
        try {
          filters.parseFilter(stack, questFile.holderLookup())
        } catch (e) {
          bad.push(`${where}: filter doesn't parse: ${e}`)
        }
      }
    })
    bad.forEach(b => console.error(`[smoke-checks] quest book: ${b}`))
    console.info(`[smoke-checks] quest book: ${tasks.size()} item tasks (${filterCount} filters), ${bad.length} broken`)
    // tools/smoke.py waits for this line before it runs /reload.
    console.info('[smoke-checks] done')
    if (bad.length) throw new Error(`[smoke-checks] quest book: ${bad.length} broken item task(s)`)
  })

  // Fowl Play's birds spawn by TFC's climate rule (kubejs/startup_scripts/fowl_play.js), which replaces
  // Fowl Play's own rule in the same NeoForge event. If Fowl Play's registration ever ran after it, its rule
  // would be OR'ed back in and birds would spawn in any climate. 40 blocks above the world spawn Fowl
  // Play's own rule passes for every bird (its "mid-air spawn"), so there only the climate may decide.
  var $SpawnPlacements = Java.loadClass('net.minecraft.world.entity.SpawnPlacements')
  var $MobSpawnType = Java.loadClass('net.minecraft.world.entity.MobSpawnType')
  var $Heightmap = Java.loadClass('net.minecraft.world.level.levelgen.Heightmap$Types')
  var $BlockPos = Java.loadClass('net.minecraft.core.BlockPos')
  var $ResourceLocation = Java.loadClass('net.minecraft.resources.ResourceLocation')
  var $Registries = Java.loadClass('net.minecraft.core.registries.BuiltInRegistries')
  var $Fauna = Java.loadClass('net.dries007.tfc.common.entities.Fauna')
  var $ChunkData = Java.loadClass('net.dries007.tfc.world.chunkdata.ChunkData')
  var $Solar = Java.loadClass('net.dries007.tfc.client.overworld.SolarCalculator')
  var level = event.server.overworld()
  var spawn = level.getSharedSpawnPos()
  var pos = new $BlockPos(spawn.getX(), level.getHeight($Heightmap.WORLD_SURFACE, spawn.getX(), spawn.getZ()) + 40, spawn.getZ())
  var chunkData = $ChunkData.get(level, pos)
  var north = $Solar.getInNorthernHemisphere(pos, level)
  var birdResults = []
  var birdErrors = []
  var climateRejects = 0
  ;['blue_jay', 'cardinal', 'chickadee', 'crow', 'goose', 'gull', 'hawk', 'pigeon', 'raven', 'robin', 'sparrow'].forEach(bird => {
    var id = $ResourceLocation.parse(`fowlplay:${bird}`)
    var fauna = $Fauna.MANAGER.get(id)
    if (fauna == null) {
      birdErrors.push(`${id}: no TFC fauna definition`)
      return
    }
    var climate = fauna.climate().isValid(chunkData, pos, level.getRandom(), north)
    var spawns = $SpawnPlacements.checkSpawnRules($Registries.ENTITY_TYPE.get(id), level, $MobSpawnType.NATURAL, pos, level.getRandom())
    if (!climate) climateRejects++
    birdResults.push(`${bird} ${climate ? 'fits' : 'doesn\'t fit'}${spawns == climate ? '' : ' but ' + (spawns ? 'spawns' : 'doesn\'t spawn')}`)
    if (spawns != climate) birdErrors.push(`${id}: the climate ${climate ? 'fits' : 'doesn\'t fit'} at ${pos.toShortString()}, but the spawn rule says ${spawns}`)
  })
  console.info(`[smoke-checks] Fowl Play spawn rules at ${pos.toShortString()}: ${birdResults.join(', ')}`)
  if (climateRejects == 0) console.warn('[smoke-checks] Fowl Play: every bird fits the climate at the world spawn, so the check is inconclusive')
  birdErrors.forEach(e => console.error(`[smoke-checks] Fowl Play: ${e}`))
  if (birdErrors.length) throw new Error(`[smoke-checks] Fowl Play: ${birdErrors.length} bird(s) don't spawn by TFC's climate rule`)
})

// Complicated Bees' crafted nests (kubejs/server_scripts/compat/complicated_bees.js): a nest item carries its
// species in the block entity data the mod's own item and block read (BeeNestBlockItem, BeeNestBlock). A
// nest without it would place a speciesless nest, so check each recipe's result.
ServerEvents.loaded(event => {
  var $ResourceLocation2 = Java.loadClass('net.minecraft.resources.ResourceLocation')
  var $DataComponents = Java.loadClass('net.minecraft.core.component.DataComponents')
  var recipes = event.server.getRecipeManager()
  var bad = []
  ;['forest', 'plains', 'desert', 'jungle'].forEach(species => {
    var holder = recipes.byKey($ResourceLocation2.parse(`pack:complicated_bees/${species}_nest`))
    if (!holder.isPresent()) { bad.push(`${species}: recipe missing`); return }
    var out = holder.get().value().getResultItem(event.server.registryAccess())
    var data = out.get($DataComponents.BLOCK_ENTITY_DATA)
    var tag = data ? data.copyTag() : null
    var found = tag ? String(tag.getString('species')) : ''
    console.info(`[smoke-checks] bee nest ${species}: ${out.getHoverName().getString()} species=${found}`)
    if (found !== `complicated_bees:${species}`) bad.push(`${species}: block entity data ${tag}`)
  })
  bad.forEach(b => console.error(`[smoke-checks] bee nest: ${b}`))
  if (bad.length) throw new Error(`[smoke-checks] bee nest: ${bad.length} wrong`)
})

// Sophisticated Storage and Backpacks refuse what a TFC chest refuses (mod/ pack_world, StorageSizeMixin; docs/design.md,
// "Sophisticated Backpacks"). Through the item handler a hopper, a Create funnel or AE2 would use: oversized TFC items (a log, an
// anvil, a large vessel) are refused by a chest, a barrel, a limited barrel, a shulker box and a backpack's inventory, ordinary ones
// are taken, and an oversized item a storage already holds can be taken out.
ServerEvents.loaded(event => {
  event.server.scheduleInTicks(5, () => {
    try {
      var $Cap = Java.loadClass('net.neoforged.neoforge.capabilities.Capabilities$ItemHandler')
      var $RL = Java.loadClass('net.minecraft.resources.ResourceLocation')
      var $Reg = Java.loadClass('net.minecraft.core.registries.BuiltInRegistries')
      var level = event.server.overworld()
      var base = level.getSharedSpawnPos().above(60)
      level.getChunk(base)
      var bad = []
      var refuse = ['tfc:wood/log/oak', 'tfc:metal/anvil/bronze', 'tfc:ceramic/large_vessel']
      var accept = ['tfc:metal/ingot/copper', 'tfc:ore/small_native_copper', 'tfc:powder/saltpeter']
      var tools = ['tfc:metal/pickaxe/copper', 'gtceu:bronze_hammer', 'tfc:metal/sword/copper']
      var probe = function (label, handler, inner, toolsOk) {
        if (!handler) { bad.push(`${label}: no item handler`); return }
        refuse.forEach(id => {
          if (handler.insertItem(0, Item.of(id), true).getCount() !== 1) bad.push(`${label}: took ${id}`)
          if (handler.isItemValid(0, Item.of(id))) bad.push(`${label}: isItemValid says yes for ${id}`)
        })
        accept.forEach(id => {
          if (handler.insertItem(0, Item.of(id), true).getCount() !== 0) bad.push(`${label}: refused ${id}`)
        })
        tools.forEach(id => {
          var left = handler.insertItem(0, Item.of(id), true).getCount()
          if (toolsOk && left !== 0) bad.push(`${label}: refused the tool ${id}`)
          if (!toolsOk && left !== 1) bad.push(`${label}: took the tool ${id}`)
        })
        // already inside: setStackInSlot is what loading a save does; taking it out must work
        inner.setStackInSlot(0, Item.of('tfc:wood/log/oak'))
        var out = handler.extractItem(0, 1, false)
        if (out.isEmpty() || out.getItem().toString().indexOf('log') < 0) bad.push(`${label}: could not take out a log that was already inside`)
      }
      ;['sophisticatedstorage:chest', 'sophisticatedstorage:barrel', 'sophisticatedstorage:limited_barrel_1', 'sophisticatedstorage:shulker_box'].forEach((id, i) => {
        var pos = base.offset(i * 3, 0, 0)
        level.getChunk(pos)
        level.setBlock(pos, $Reg.BLOCK.get($RL.parse(id)).defaultBlockState(), 3)
        var h = level.getCapability($Cap.BLOCK, pos, null)
        probe(id, h, level.getBlockEntity(pos).getStorageWrapper().getInventoryHandler(), false)
        level.setBlock(pos, Block.getBlock('minecraft:air').defaultBlockState(), 3)
      })
      // a plain backpack stack has no item handler capability; its inventory handler is what pickup and magnet upgrades insert into
      var pack = Item.of('sophisticatedbackpacks:backpack')
      var packHandler = Java.loadClass('net.p3pp3rf1y.sophisticatedbackpacks.backpack.wrapper.BackpackWrapper').fromStack(pack).getInventoryHandler()
      probe('sophisticatedbackpacks:backpack', packHandler, packHandler, true)
      bad.forEach(b => console.error(`[smoke-checks] storage size: ${b}`))
      console.info(`[smoke-checks] storage size: chest, barrel, limited barrel, shulker box and backpack checked, ${bad.length} wrong`)
      if (bad.length) throw new Error(`[smoke-checks] storage size: ${bad.length} wrong`)
    } catch (e) {
      console.error(`[smoke-checks] storage size: check failed to run: ${e}`)
      throw e
    }
  })
})

// Exploration rewards and building helpers (kubejs/server_scripts/compat/exploration.js, building_helpers.js, world/place_titles.js,
// kubejs/data/artifacts, kubejs/data/littlejoys, kubejs/data/paraglider; docs/design.md, "Exploration rewards"): the recipes are
// the pack's (Comforts' rope and nail from TFC Huts, the TFC carrot, the stick tiers), the campsite (single chest, TFC chests) is
// added to TFC's biomes and the statues of Paragliders are in none, the dig spot recipes load, and the place titles find the
// places they should.
ServerEvents.loaded(event => {
  event.server.scheduleInTicks(10, () => {
    var bad = []
    try {
      var $RL3 = Java.loadClass('net.minecraft.resources.ResourceLocation')
      var $Registries = Java.loadClass('net.minecraft.core.registries.Registries')
      var $TagKey = Java.loadClass('net.minecraft.tags.TagKey')
      var access = event.server.registryAccess()
      var recipes = event.server.getRecipeManager()
      var recipe = function (id) {
        var h = recipes.byKey($RL3.parse(id))
        return h.isPresent() ? h.get().value() : null
      }
      ;['comforts:rope_and_nail_shapeless_tfc', 'comforts:sleeping_bag_white', 'comforts:hammock_white', 'paraglider:paraglider',
        'paraglider:energizing_mixture', 'constructionstick:copper_stick', 'constructionstick:iron_stick', 'constructionstick:diamond_stick',
        'constructionstick:netherite_stick', 'constructionstick:template_angel', 'constructionstick:template_battery', 'measurements:tape_measure', 'pack:paraglider/goddess_statue', 'paraglider:goddess_statue/heart_container', 'paraglider:goddess_statue/stamina_vessel',
        'littlejoys:dig_spot/tfc_grass', 'littlejoys:dig_spot/tfc_dirt', 'littlejoys:dig_spot/tfc_clay', 'littlejoys:dig_spot/tfc_mud',
        'littlejoys:dig_spot/tfc_sand', 'littlejoys:dig_spot/tfc_gravel', 'littlejoys:fishing_spot/water', 'littlejoys:fishing_spot/tfc_salt_water'].forEach(id => {
        if (!recipe(id)) bad.push(`recipe ${id} is missing`)
      })
      ;['comforts:rope_and_nail', 'comforts:shapeless_rope_and_nail', 'constructionstick:template_destruction', 'artifacts:eternal_steak_furnace'].forEach(id => {
        if (recipe(id)) bad.push(`recipe ${id} should be gone`)
      })
      // stick tiers: what each takes in the ingot's place
      var takes = function (id, item) {
        var r = recipe(id)
        if (!r) return false
        var ings = r.getIngredients()
        for (var i = 0; i < ings.size(); i++) if (ings.get(i).test(Item.of(item))) return true
        return false
      }
      if (!takes('constructionstick:iron_stick', 'tfc:metal/ingot/wrought_iron')) bad.push('iron stick does not take a wrought iron ingot')
      if (takes('constructionstick:iron_stick', 'tfc:gem/diamond')) bad.push('iron stick takes a diamond')
      if (!takes('constructionstick:diamond_stick', 'tfc:metal/ingot/steel')) bad.push('diamond stick does not take a steel ingot')
      if (takes('constructionstick:diamond_stick', 'tfc:gem/diamond')) bad.push('diamond stick still takes a diamond')
      if (!takes('constructionstick:netherite_stick', 'tfc:metal/ingot/red_steel')) bad.push('netherite stick does not take a red steel ingot')
      if (!takes('paraglider:energizing_mixture', 'tfc:food/carrot')) bad.push('energizing mixture does not take a TFC carrot')
      if (takes('paraglider:energizing_mixture', 'minecraft:carrot')) bad.push('energizing mixture still takes a vanilla carrot')
      if (!takes('constructionstick:template_battery', 'tfc:food/potato')) bad.push('battery template does not take a TFC potato')

      if (recipe('paraglider:horned_statue/buy_heart_container') && !recipe('paraglider:goddess_statue/heart_container')) bad.push('statue bargains missing')
      if (!takes('pack:paraglider/goddess_statue', 'tfc:metal/ingot/gold')) bad.push('goddess statue does not take a gold ingot')

      // the campsite: in TFC's land biomes, a single chest, TFC chests
      var biomes = access.registryOrThrow($Registries.BIOME)
      var hasCampsite = function (biomeId) {
        var b = biomes.get($RL3.parse(biomeId))
        if (!b) return null
        var steps = b.getGenerationSettings().features()
        for (var s = 0; s < steps.size(); s++) {
          var step = steps.get(s)
          for (var f = 0; f < step.size(); f++) {
            var key = step.get(f).unwrapKey()
            if (key.isPresent() && String(key.get().location()).indexOf('artifacts:') === 0) return String(key.get().location())
          }
        }
        return ''
      }
      ;['tfc:plains', 'tfc:hills', 'tfc:mountains', 'tfc:ocean'].forEach(b => {
        var got = hasCampsite(b)
        if (got !== 'artifacts:underground_minimalist_campsite') bad.push(`${b} has campsite feature ${got}`)
      })
      var placed = access.registryOrThrow($Registries.PLACED_FEATURE).get($RL3.parse('artifacts:underground_minimalist_campsite'))
      if (!placed) bad.push('placed feature artifacts:underground_minimalist_campsite is missing')
      else {
        var mods = placed.placement()
        for (var m = 0; m < mods.size(); m++) {
          if (String(mods.get(m)).toLowerCase().indexOf('configvaluefilter') >= 0) bad.push('the minimalist campsite still checks the mod config')
        }
      }
      var chestTag = $TagKey.create($Registries.BLOCK, $RL3.parse('artifacts:campsite_chests'))
      var chestIds = []
      var chests = Java.loadClass('net.minecraft.core.registries.BuiltInRegistries').BLOCK.getTagOrEmpty(chestTag).iterator()
      while (chests.hasNext()) chestIds.push(String(chests.next().unwrapKey().get().location()))
      if (chestIds.indexOf('tfc:wood/chest/oak') < 0) bad.push('campsite chests do not include a TFC chest')
      if (chestIds.indexOf('minecraft:chest') >= 0) bad.push('campsite chests still include the vanilla chest')

      // the statues of Paragliders generate nowhere
      var structures = access.registryOrThrow($Registries.STRUCTURE)
      ;['underground_horned_statue', 'tarrey_town_goddess_statue', 'nether_horned_statue'].forEach(n => {
        var st = structures.get($RL3.parse(`paraglider:${n}`))
        if (!st) { bad.push(`structure paraglider:${n} is missing`); return }
        if (st.biomes().size() !== 0) bad.push(`structure paraglider:${n} is in ${st.biomes().size()} biomes`)
      })

      // place titles: real places from their coordinates, the list as the mod has it
      var $Projection = Java.loadClass('net.yazloysasha.tfcrealworld.util.projection.ProjectionManager')
      var all = placesLoad()
      if (all.length < 400) bad.push(`place titles know only ${all.length} places`)
      ;[['Rome', 41.89, 12.50], ['Paris', 48.86, 2.35], ['Hobart', -42.88, 147.33], ['Stonehenge', 51.1789, -1.8262]].forEach(p => {
        var xz = $Projection.geographicToClassic(p[2], p[1])
        var w = placesNearest(Math.round(xz[0]), Math.round(xz[1]), null)
        console.info(`[smoke-checks] place titles: ${p[0]} at ${Math.round(xz[0])},${Math.round(xz[1])} -> ${w ? w.title + ' / ' + w.subtitle : 'nothing'}`)
        if (!w || w.title.indexOf(p[0]) < 0) bad.push(`place titles: ${p[0]} found ${w ? w.title : 'nothing'}`)
      })
      var mid = $Projection.geographicToClassic(-40.0, 30.0)
      if (placesNearest(Math.round(mid[0]), Math.round(mid[1]), null)) bad.push('place titles: a title in the middle of the Atlantic')
    } catch (e) {
      bad.push(`check failed to run: ${e}`)
    }
    bad.forEach(b => console.error(`[smoke-checks] exploration: ${b}`))
    console.info(`[smoke-checks] exploration: recipes, campsite, statues and place titles checked, ${bad.length} wrong`)
    if (bad.length) throw new Error(`[smoke-checks] exploration: ${bad.length} wrong`)
  })
})

// Sea-floor deposits (kubejs/startup_scripts/sea_floor.js, kubejs/data/pack/worldgen/*/ocean/; docs/design.md, "Deep sea"): the six
// blocks exist, none of the five cubes can be waterlogged (vanilla water in a TFC ocean), the loose nodule is TFC's ground cover and
// can hold TFC salt water, every block drops a GregTech raw ore through its data loot table (not KubeJS's default of itself), and
// the nodule features loaded.
ServerEvents.loaded(event => {
  event.server.scheduleInTicks(10, () => {
    var bad = []
    try {
      var $RL4 = Java.loadClass('net.minecraft.resources.ResourceLocation')
      var $BuiltIn = Java.loadClass('net.minecraft.core.registries.BuiltInRegistries')
      var $Reg4 = Java.loadClass('net.minecraft.core.registries.Registries')
      var $Ground = Java.loadClass('net.dries007.tfc.common.blocks.GroundcoverBlock')
      var $Props = Java.loadClass('net.minecraft.world.level.block.state.properties.BlockStateProperties')
      var $BlockCls = Java.loadClass('net.minecraft.world.level.block.Block')
      var $BP = Java.loadClass('net.minecraft.core.BlockPos')
      var rl = function (id) { return $RL4.parse(id) }
      var level = event.server.overworld()
      ;['sulfide_chimney', 'sulfide_mound', 'anhydrite_chimney', 'nodule_bed', 'mn_crust', 'nodule'].forEach(n => {
        if (!$BuiltIn.BLOCK.containsKey(rl('pack:' + n))) { bad.push(`block pack:${n} is missing`); return }
        var b = $BuiltIn.BLOCK.get(rl('pack:' + n))
        var st = b.defaultBlockState()
        if (n != 'nodule' && st.hasProperty($Props.WATERLOGGED)) bad.push(`pack:${n} is waterloggable`)
        var drops = $BlockCls.getDrops(st, level, new $BP(0, 0, 0), null)
        var ids = []
        for (var i = 0; i < drops.size(); i++) ids.push(String(drops.get(i).getItem().builtInRegistryHolder().key().location()))
        if (!ids.some(i => i.indexOf('gtceu:raw_') == 0)) bad.push(`pack:${n} drops [${ids}], no GregTech raw ore: the loot table did not override`)
        if (n == 'nodule') {
          if (!(b instanceof $Ground)) bad.push('pack:nodule is not a TFC GroundcoverBlock')
          else if (!b.getFluidProperty().canContain($BuiltIn.FLUID.get(rl('tfc:salt_water')))) bad.push('pack:nodule cannot hold TFC salt water')
        }
      })
      var access = event.server.registryAccess()
      var cf = access.registryOrThrow($Reg4.CONFIGURED_FEATURE), pf = access.registryOrThrow($Reg4.PLACED_FEATURE)
      ;['nodule_field', 'nodule_bed_disc', 'nodule_scatter', 'nodule_lump'].forEach(n => {
        if (!cf.containsKey(rl('pack:ocean/' + n))) bad.push(`configured feature pack:ocean/${n} did not load`)
        if (!pf.containsKey(rl('pack:ocean/' + n))) bad.push(`placed feature pack:ocean/${n} did not load`)
      })
    } catch (e) {
      bad.push(`check failed to run: ${e}`)
    }
    bad.forEach(b => console.error(`[smoke-checks] sea floor: ${b}`))
    console.info(`[smoke-checks] sea floor: blocks, drops, groundcover and nodule features checked, ${bad.length} wrong`)
    if (bad.length) throw new Error(`[smoke-checks] sea floor: ${bad.length} wrong`)
  })
})
